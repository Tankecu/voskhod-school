/* сборка: выдаёт count вопросов нужной сложности */
window.BANK_RW_ITEMS_DRAW = function (difficulty, count, exclude) {
  var pool = window.BANK_RW_ITEMS.filter(function (q) {
    return q.difficulty === difficulty && (!exclude || exclude.indexOf(q) === -1);
  });
  var out = [];
  var copy = pool.slice();
  while (out.length < count && copy.length) {
    var i = Math.floor(Math.random() * copy.length);
    out.push(copy.splice(i, 1)[0]);
  }
  /* если рукописных не хватило — добираем любой сложностью */
  if (out.length < count) {
    var extra = window.BANK_RW_ITEMS.filter(function (q) {
      return q.difficulty !== difficulty && exclude.indexOf(q) === -1 && out.indexOf(q) === -1;
    });
    while (out.length < count && extra.length) {
      var j = Math.floor(Math.random() * extra.length);
      out.push(extra.splice(j, 1)[0]);
    }
  }
  return out;
};
